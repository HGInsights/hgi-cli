#!/usr/bin/env node
// Embeds skills/hgi/SKILL.md as a TypeScript string so the npm build and the single-file binaries
// carry the same bytes and `hgi skill install` needs no file next to the executable.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const skill = readFileSync(resolve(root, 'skills/hgi/SKILL.md'), 'utf8');
const out = resolve(root, 'src/generated/skill-md.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/gen-skill-md.mjs from skills/hgi/SKILL.md. Do not edit.\nexport const SKILL_MD = ${JSON.stringify(skill)};\n`,
);
