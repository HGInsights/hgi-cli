export async function readStdin(): Promise<string> {
  const chunks: Buffer[] = [];
  for await (const chunk of process.stdin) chunks.push(Buffer.from(chunk as Buffer));
  return Buffer.concat(chunks).toString('utf8');
}

function stderrWantsJson(): boolean {
  return !process.stderr.isTTY || process.argv.includes('--json-errors');
}

/** One credit line on stderr: `credit_cost: 3`, or `{"credit_cost":3}` when stderr is not a terminal. */
export function reportCredit(cost: number | null): void {
  process.stderr.write(stderrWantsJson() ? `${JSON.stringify({ credit_cost: cost })}\n` : `credit_cost: ${cost ?? 'unknown'}\n`);
}

export type RetryCode = 'rate_limited' | 'load_shed' | 'not_established' | 'governance_unavailable';

export interface RetryEvent {
  attempt: number;
  max: number;
  code: RetryCode;
  wait_seconds: number;
}

/** Rounds a wait to one decimal place, the precision the retry line reports. */
export function roundWait(ms: number): number {
  return Math.round(ms / 100) / 10;
}

/**
 * One line on stderr before every retry's wait: `hgi: retry 2/6: rate_limited, waiting 12s`, or
 * `{"retry":{...}}` when stderr is not a terminal. Every field is generated by hgi, never server text.
 */
export function reportRetry(e: RetryEvent): void {
  const event: RetryEvent = { attempt: e.attempt, max: e.max, code: e.code, wait_seconds: e.wait_seconds };
  process.stderr.write(
    stderrWantsJson()
      ? `${JSON.stringify({ retry: event })}\n`
      : `hgi: retry ${event.attempt}/${event.max}: ${event.code}, waiting ${event.wait_seconds}s\n`,
  );
}
